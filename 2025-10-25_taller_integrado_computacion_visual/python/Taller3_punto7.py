def process_and_annotate(img_bgr, hands, game=None):
    annotated = img_bgr.copy()
    h, w = annotated.shape[:2]
    img_rgb = cv2.cvtColor(annotated, cv2.COLOR_BGR2RGB)
    results = hands.process(img_rgb)
    finger_index_pos = None
    if results.multi_hand_landmarks:
        for hand_landmarks, handedness in zip(results.multi_hand_landmarks, results.multi_handedness):
            label = handedness.classification[0].label  # 'Left' or 'Right' as detected (after mirror if used)
            mp_drawing.draw_landmarks(annotated, hand_landmarks, mp_hands.HAND_CONNECTIONS)
            total, fingers = count_fingers(hand_landmarks, label)
            lm = hand_landmarks.landmark
            thumb_px = landmark_to_pixel(lm[4], w, h)
            index_px = landmark_to_pixel(lm[8], w, h)
            finger_index_pos = index_px
            pinch_d = int(np.linalg.norm(np.array(thumb_px) - np.array(index_px)))
            # gesture mapping
            if total == 0:
                gesture = "Puño"
            elif total == 5:
                gesture = "Mano abierta"
            elif fingers.get('index', 0) == 1 and fingers.get('middle', 0) == 1 and fingers.get('ring', 0) == 0:
                gesture = "Peace"
            elif pinch_d < 40:
                gesture = "Pinch"
            else:
                gesture = f"{total} dedos"
            cv2.putText(annotated, f"{label} {gesture}", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1.0, (255,255,255), 2)
            cv2.circle(annotated, thumb_px, 6, (0,255,0), -1)
            cv2.circle(annotated, index_px, 6, (0,0,255), -1)
            cv2.line(annotated, thumb_px, index_px, (255, 0, 0), 2)
            cv2.putText(annotated, f"d={pinch_d}", (index_px[0]+10, index_px[1]+10), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (200,200,0), 2)
            # show finger states
            y0 = 60
            for i,(k,v) in enumerate(fingers.items()):
                cv2.putText(annotated, f"{k}:{v}", (10, y0 + i*20), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (180,180,180), 1)
    else:
        cv2.putText(annotated, "No hands", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1.0, (150,150,150), 2)

    # game drawing (single-target uses index finger)
    if game is not None:
        if 'finger_index_pos' in locals() and finger_index_pos is not None:
            _ = game.update_and_check(finger_index_pos)
        # draw target and score
        cv2.circle(annotated, game.target_pos, game.target_radius, (0,165,255), -1)
        cv2.putText(annotated, f"Score: {game.score}", (w - 170, 30), cv2.FONT_HERSHEY_SIMPLEX, 1.0, (0,255,0), 2)

    return annotated

def run_colab(max_seconds=None, target_w=640, target_h=480, fps=8, show_game=True, mirror=True):
    """
    Ejecuta la demo en Colab hasta que:
      - max_seconds transcurran (si no es None), o
      - el usuario pulse el botón 'Stop Stream' creado en la página, o
      - interrumpa la celda (KeyboardInterrupt).
    Parámetros:
      mirror: si True (por defecto), voltea horizontalmente el frame ANTES de pasarlo a MediaPipe
              — así la vista es espejo y las etiquetas coinciden con la percepción del usuario.
    """
    print("Inicializando cámara en la página (permite permisos si el navegador lo solicita)...")
    res = init_camera_page()
    if not res or 'error' in str(res):
        raise RuntimeError(f"No se pudo inicializar la cámara: {res}")
    make_stop_button()

    hands = mp_hands.Hands(static_image_mode=False, max_num_hands=2,
                           min_detection_confidence=0.6, min_tracking_confidence=0.6)
    game = SimpleCatchGame(target_w, target_h) if show_game else None

    display_handle = display(IPyImage(b''), display_id=True)

    start = time.time()
    frame_count = 0
    try:
        while True:
            # Condiciones de salida
            if max_seconds is not None and (time.time() - start) > max_seconds:
                print("Tiempo máximo alcanzado, saliendo...")
                break
            if check_stop_requested():
                print("Stop solicitado desde la página.")
                break

            dataurl = capture_frame_dataurl()
            if not dataurl:
                time.sleep(0.15)
                continue
            if isinstance(dataurl, str) and dataurl.startswith('error:'):
                print("JS capture error:", dataurl)
                time.sleep(0.5)
                continue

            img = dataurl_to_cv2_img(dataurl)
            if img is None:
                time.sleep(0.15)
                continue

            # Aplicar espejo antes de procesar si mirror=True
            if mirror:
                img = cv2.flip(img, 1)

            img = cv2.resize(img, (target_w, target_h))
            annotated = process_and_annotate(img, hands, game=game)

            # encode to jpeg bytes y actualizar display
            _, jpg = cv2.imencode('.jpg', annotated, [int(cv2.IMWRITE_JPEG_QUALITY), 85])
            display_handle.update(IPyImage(data=jpg.tobytes()))
            frame_count += 1
            time.sleep(1.0 / max(1, fps))
    except KeyboardInterrupt:
        print("Interrumpido por usuario.")
    finally:
        print("Cerrando cámara y limpiando...")
        stop_camera_page()
        try:
            hands.close()
        except Exception:
            pass
        print(f"Frames procesados: {frame_count}")
        return frame_count

