mp_drawing = mp.solutions.drawing_utils
mp_hands = mp.solutions.hands

def count_fingers(hand_landmarks, handedness_label):
    tips = [4, 8, 12, 16, 20]
    pip_ids = {4: 3, 8: 6, 12: 10, 16: 14, 20: 18}
    lm = hand_landmarks.landmark
    fingers = {}
    # Thumb: comparación horizontal depende de mano
    try:
        if handedness_label == 'Right':
            fingers['thumb'] = 1 if lm[4].x < lm[3].x else 0
        else:
            fingers['thumb'] = 1 if lm[4].x > lm[3].x else 0
    except Exception:
        fingers['thumb'] = 0
    for tip in [8, 12, 16, 20]:
        name = {8: 'index', 12: 'middle', 16: 'ring', 20: 'pinky'}[tip]
        try:
            fingers[name] = 1 if lm[tip].y < lm[pip_ids[tip]].y else 0
        except Exception:
            fingers[name] = 0
    total = sum(fingers.values())
    return total, fingers

def landmark_to_pixel(landmark, w, h):
    return int(landmark.x * w), int(landmark.y * h)

# ------------------ Simple minijuego "Catch" ------------------

class SimpleCatchGame:
    def __init__(self, w, h):
        self.w = w
        self.h = h
        self.reset()

    def reset(self):
        self.target_radius = 30
        self.target_pos = (np.random.randint(50, self.w - 50), np.random.randint(50, self.h - 50))
        self.score = 0
        self.last_catch = time.time()

    def update_and_check(self, finger_pos):
        if finger_pos is None:
            return False
        d = np.linalg.norm(np.array(finger_pos) - np.array(self.target_pos))
        caught = d < (self.target_radius + 24)
        if caught:
            self.score += 1
            self.target_pos = (np.random.randint(50, self.w - 50), np.random.randint(50, self.h - 50))
            self.last_catch = time.time()
        # movimiento suave
        if time.time() - self.last_catch > 0.5:
            dx = np.random.randint(-4, 5)
            dy = np.random.randint(-4, 5)
            x = np.clip(self.target_pos[0] + dx, 50, self.w - 50)
            y = np.clip(self.target_pos[1] + dy, 50, self.h - 50)
            self.target_pos = (int(x), int(y))
        return caught

